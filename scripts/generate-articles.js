const fs = require("fs");
const path = require("path");

const dataPath = path.join(__dirname, "../data/articles.json");
const articlesDir = path.join(__dirname, "../articles");

const SITE_URL = "https://ahmad-alarag.netlify.app";
const GENERATED_MARKER = "<!-- GENERATED BY generate-articles.js -->";

const data = JSON.parse(fs.readFileSync(dataPath, "utf8"));
const articles = Array.isArray(data.articles) ? data.articles : [];

fs.mkdirSync(articlesDir, { recursive: true });

function escapeHtml(value = "") {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function markdownToHtml(value = "") {
  return escapeHtml(value)
    .replace(/^### (.*)$/gm, "<h3>$1</h3>")
    .replace(/^## (.*)$/gm, "<h2>$1</h2>")
    .replace(/^# (.*)$/gm, "<h1>$1</h1>")
    .replace(/\*\*(.*?)\*\*/g, "<strong>$1</strong>")
    .replace(/\*(.*?)\*/g, "<em>$1</em>")
    .split(/\n\s*\n/)
    .map(paragraph => `<p>${paragraph.replace(/\n/g, "<br>")}</p>`)
    .join("\n");
}

for (const article of articles) {
  if (!article.title || !article.content || !article.url) continue;
  if (!article.url.startsWith("/articles/")) continue;

  const slug = article.url
    .replace(/^\/articles\//, "")
    .replace(/\/+$/, "");

  if (!/^[a-zA-Z0-9-]+$/.test(slug)) continue;

  const outputPath = path.join(articlesDir, `${slug}.html`);

  // لا تستبدل الصفحات اليدوية الموجودة
  if (fs.existsSync(outputPath)) {
    const existing = fs.readFileSync(outputPath, "utf8");
    if (!existing.includes(GENERATED_MARKER)) {
      console.log(`تم الحفاظ على الصفحة اليدوية: ${slug}`);
      continue;
    }
  }

  const title = escapeHtml(article.title);
  const description = escapeHtml(article.summary || article.title);

  let image = article.image || "/ahmad-hassan-alaaraj.jpg";

  if (!/^https?:\/\//i.test(image)) {
    image = image.startsWith("/") ? image : `/${image}`;
    image = `${SITE_URL}${image}`;
  }

  const content = markdownToHtml(article.content);
  const date = escapeHtml(article.date || "");
  const articleUrl = `${SITE_URL}/articles/${slug}`;

  const html = `${GENERATED_MARKER}
<!doctype html>
<html lang="ar" dir="rtl">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title} | أحمد حسن الأعرج</title>
<meta name="description" content="${description}">
<link rel="canonical" href="${articleUrl}">
<meta property="og:type" content="article">
<meta property="og:title" content="${title}">
<meta property="og:description" content="${description}">
<meta property="og:url" content="${articleUrl}">
<meta property="og:image" content="${escapeHtml(image)}">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="${title}">
<meta name="twitter:description" content="${description}">
<meta name="twitter:image" content="${escapeHtml(image)}">
<style>
body {
  margin: 0;
  background: #f4f5f2;
  color: #26332d;
  font-family: Tahoma, Arial, sans-serif;
  line-height: 2;
}
header {
  background: #173d32;
  color: white;
  padding: 24px;
  text-align: center;
}
main {
  max-width: 850px;
  margin: 35px auto;
  padding: 30px;
  background: white;
  border-radius: 12px;
}
.category { color: #a83232; }
.article-date {
  color: #777;
  font-size: 14px;
  margin-top: -8px;
}
h1 { color: #173d32; line-height: 1.6; }
.article-content { font-size: 18px; }
footer {
  text-align: center;
  padding: 25px;
  color: #666;
}
a { color: #a83232; }
@media (max-width: 600px) {
  main { margin: 15px; padding: 20px; }
}
</style>
</head>
<body>
<header>
  <h2>أحمد حسن الأعرج | كاتب وإعلامي فلسطيني</h2>
</header>
<main>
  <div class="category">${escapeHtml(article.category || "مقال")}</div>
  <h1>${title}</h1>
  ${date ? `<p class="article-date">${date}</p>` : ""}
  <p>✍🏻 أحمد حسن الأعرج</p>
  <hr>
  <div class="article-content">${content}</div>
  <p><a href="../index.html#articles">العودة إلى المقالات</a></p>
</main>
<footer>© أحمد حسن الأعرج</footer>
</body>
</html>`;

  fs.writeFileSync(outputPath, html, "utf8");
  console.log(`تم إنشاء أو تحديث صفحة المقال: ${slug}`);
}
